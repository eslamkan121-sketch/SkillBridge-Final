def family_for_title(title):
    """Curated exact-title family lookup, punctuation-tolerant.

    Returns the family key for a title that appears in ROLE_FAMILY_BLUEPRINT
    (or a close punctuation variant of it) and ``None`` otherwise. The curated
    map already carries the common variants ("ui/ux designer" and "ui ux
    designer", "full stack" and "full-stack"); this resolver additionally
    tolerates separator drift so "DevOps / Platform Engineer" still hits
    "devops / platform engineer" after normal whitespace collapsing.
    """
    key = " ".join((title or "").strip().lower().split()).strip()
    hit = ROLE_FAMILY_BLUEPRINT.get(key)
    if hit:
        return hit
    for sep in ("/", "-", "&", "_"):
        alt = " ".join(key.replace(sep, " ").split())
        if alt and alt != key:
            hit = ROLE_FAMILY_BLUEPRINT.get(alt)
            if hit:
                return hit
    return None

