def _slugify(title):
    import re
    return re.sub(r"[^a-z0-9]+", "-", (title or "").strip().lower()).strip("-")


def build_blueprint_scenarios(role_title, role_skills):
    """Deterministic role-blueprint fallback scenarios for a target role with NO
    family. Each uses the role's OWN required skills as the scenario skills, so
    practice always overlaps the role requirements — and never a security
    scenario. The same title and skill set always produce the same scenarios."""
    import re as _re
    skills = [s for s in (role_skills or []) if s][:4]
    if not skills:
        skills = ["Problem Solving", "Communication", "Time Management", "Documentation"]
    slug = (_slugify(role_title) or "role").strip("-")[:60].strip("-")
    component_cycle = ["investigation", "threat_analysis", "decision_making", "incident_response"]
    out = []
    for i, tpl in enumerate(BLUEPRINT_TEMPLATES):
        step_map = {}
        built_steps = []
        for step in tpl["steps"]:
            step_map[step["id"]] = step["id"]
            s = dict(step)
            s["situation"] = s.get("situation", "").replace("{role}", role_title)
            if s.get("multi"):
                opts = []
                for o in s.get("options", []):
                    oo = dict(o)
                    oo["label"] = o["label"].replace("{role}", role_title)
                    opts.append(oo)
                s["options"] = opts
            for d in s.get("decisions", []):
                dd = dict(d)
                dd["feedback"] = d.get("feedback", "").replace("{role}", role_title)
                dd["consequence"] = d.get("consequence", "").replace("{role}", role_title)
                dd["component"] = _re.sub(r"^[\"']", "", str(d.get("component") or "decision_making"))
            built_steps.append(s)
        outcomes = {}
        for key, oc in tpl["outcomes"].items():
            oo = dict(oc)
            oo["summary"] = oc.get("summary", "").replace("{role}", role_title)
            outcomes[key] = oo
        skills_components = {}
        for idx, sk in enumerate(skills):
            skills_components[sk] = component_cycle[idx % len(component_cycle)]
        out.append({
            "id": f"bp-{slug}-{i + 1}",
            "title": tpl["title"].replace("{role}", role_title),
            "description": tpl["description"].replace("{role}", role_title),
            "role_title": role_title,
            "family": "generic",
            "role_families": ["generic"],
            "difficulty": tpl.get("difficulty", "beginner"),
            "estimated_minutes": tpl.get("estimated_minutes", 10),
            "category": tpl.get("category", "role_specific"),
            "version": SCENARIO_VERSION,
            "intro": (
                f"Deterministic professional practice built from the {role_title} role: "
                f"the situations below are generic to professional work but the skills you "
                f"are asked to apply come from the role's own requirements."
            ),
            "skills": skills,
            "skills_components": skills_components,
            "start_step": "step-1",
            "steps": built_steps,
            "outcomes": outcomes,
        })
    return out